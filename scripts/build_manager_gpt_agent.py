#!/usr/bin/env python3
"""build_manager_gpt_agent.py — generate agents/agent/manager-gpt.md: the Manager prompt with a GPT-only overlay.

`manager-gpt` is a second primary agent beside `manager`, for Manager Sessions run on GPT models (Dan picks it in the
agent picker). Its body is manager.md's body, unchanged, plus three GPT-only pieces from agents/manager-gpt/:
opening.md at the very start of the prompt, bridge.md just before the tool reference (the heading BRIDGE_ANCHOR), and
closing.md at the very end. The frontmatter is manager.md's, with this agent's own description and a GPT model.

Never edit manager-gpt.md by hand: edit manager.md (shared by both Managers) or the overlay files (GPT only). The
restart script regenerates this file before its config check; test_manager_gpt_agent.py fails while it is stale.
"""
from __future__ import annotations

import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "agents" / "agent" / "manager.md"
OVERLAY = REPO / "agents" / "manager-gpt"
TARGET = REPO / "agents" / "agent" / "manager-gpt.md"
BRIDGE_ANCHOR = "### Filesystem, Shell and Search"
MODEL = "openai/gpt-6.1-sol-fast#medium"
DESCRIPTION = (
    "The MANAGER for GPT models: the same Manager prompt as manager.md, with a GPT-only initiative overlay at its very "
    "start, at the hinge before the tool reference, and at its very end. Pick it in the agent picker for a Manager "
    "Session on GPT. Starts on GPT-6.1 Sol Fast at thinking level medium. Generated by "
    "scripts/build_manager_gpt_agent.py from agents/agent/manager.md and agents/manager-gpt/; never edit it by hand."
)


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def split_frontmatter(text: str) -> tuple[str, str]:
    """(frontmatter without its --- fences, body)."""
    if not text.startswith("---\n"):
        raise ValueError(f"{SOURCE.name}: no frontmatter (the file must start with ---)")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise ValueError(f"{SOURCE.name}: frontmatter is not closed by a --- line")
    return text[4:end], text[end + 5:]


def _frontmatter(source_front: str) -> str:
    """manager.md's frontmatter with this agent's description and model; every other key (mode, permissions) kept."""
    quoted = "'" + DESCRIPTION.replace("'", "''") + "'"
    out, replaced = [], set()
    for line in source_front.split("\n"):
        key = line.split(":", 1)[0] if re.match(r"^[a-z_]+:", line) else None
        if key == "description":
            out.append(f"description: {quoted}")
            replaced.add(key)
        elif key == "model":
            out.append(f"model: {MODEL}")
            replaced.add(key)
        else:
            out.append(line)
    missing = {"description", "model"} - replaced
    if missing:
        raise ValueError(f"{SOURCE.name}: frontmatter has no single-line {', '.join(sorted(missing))}")
    return "\n".join(out)


def render() -> str:
    """The full text of manager-gpt.md, from manager.md and the overlay files."""
    front, body = split_frontmatter(_read(SOURCE))
    opening = _read(OVERLAY / "opening.md").strip("\n")
    bridge = _read(OVERLAY / "bridge.md").strip("\n")
    closing = _read(OVERLAY / "closing.md").strip("\n")
    at = body.find("\n" + BRIDGE_ANCHOR)
    if at >= 0:
        body = body[:at + 1] + bridge + "\n\n" + body[at + 1:]
    else:  # the shared prompt lost its anchor: keep the reminder, just after the opening (the test flags this)
        opening = opening + "\n\n" + bridge
    return ("---\n" + _frontmatter(front) + "\n---\n" + opening + "\n\n---\n\n" + body.strip("\n")
            + "\n\n---\n\n" + closing + "\n")


def build() -> bool:
    """Write the agent file; True when it changed."""
    text = render()
    if TARGET.exists() and _read(TARGET) == text:
        return False
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    return True


if __name__ == "__main__":
    print(f"{TARGET.name}: {'regenerated' if build() else 'already current'} from {SOURCE.name} + {OVERLAY.name}/")
